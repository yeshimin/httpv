#!/bin/sh
set -eu

: "${HTTPV_UPSTREAM_URL:=http://demo:9000}"
: "${HTTPV_UPSTREAM_HOST:=demo:9000}"
: "${HTTPV_PROXY_CONNECT_TIMEOUT:=5s}"
: "${HTTPV_PROXY_READ_TIMEOUT:=60s}"
: "${HTTPV_PROXY_SEND_TIMEOUT:=60s}"
: "${HTTPV_MAX_BODY_SIZE:=64m}"
: "${HTTPV_ACCESS_LOG:=off}"
export HTTPV_UPSTREAM_URL HTTPV_UPSTREAM_HOST HTTPV_PROXY_CONNECT_TIMEOUT HTTPV_PROXY_READ_TIMEOUT HTTPV_PROXY_SEND_TIMEOUT HTTPV_MAX_BODY_SIZE HTTPV_ACCESS_LOG

envsubst '${HTTPV_UPSTREAM_URL} ${HTTPV_UPSTREAM_HOST} ${HTTPV_PROXY_CONNECT_TIMEOUT} ${HTTPV_PROXY_READ_TIMEOUT} ${HTTPV_PROXY_SEND_TIMEOUT} ${HTTPV_MAX_BODY_SIZE} ${HTTPV_ACCESS_LOG}' \
  < /usr/local/openresty/nginx/conf/nginx.conf.template \
  > /tmp/httpv-nginx.conf

exec /usr/local/openresty/bin/openresty -c /tmp/httpv-nginx.conf -g 'daemon off;'
